import * as monaco from "monaco-editor";
(self as any).MonacoEnvironment = { getWorker: () => new Worker(new URL("../../node_modules/monaco-editor/esm/vs/editor/editor.worker.js", import.meta.url), { type: "module" }) };
monaco.languages.register({ id: "probe" });
const out: string[] = [];
const model = monaco.editor.createModel("fn a() {}\nfn b() { a(); }\n", "probe", monaco.Uri.file("/r/a.rs"));
const editor = monaco.editor.create(document.getElementById("host")!, { model });
let calls = 0;
monaco.languages.registerReferenceProvider("probe", { provideReferences: () => { calls++; return [{ uri: model.uri, range: new monaco.Range(1, 4, 1, 5) }, { uri: model.uri, range: new monaco.Range(2, 10, 2, 11) }]; } });
editor.setPosition({ lineNumber: 1, column: 4 }); editor.focus();
const actions = editor.getSupportedActions().map((a) => a.id);
out.push("actions with 'refer': " + JSON.stringify(actions.filter((i) => /refer/i.test(i))));
out.push("actions with 'goto|peek|definition': " + JSON.stringify(actions.filter((i) => /goto|peek|definition/i.test(i))));
for (const id of ["editor.action.goToReferences", "editor.action.referenceSearch.trigger", "editor.action.peekDefinition"]) out.push(`getAction(${id}) = ${editor.getAction(id) ? "present" : "null"}`);
await editor.getAction("editor.action.referenceSearch.trigger")?.run(); await new Promise((r) => setTimeout(r, 600));
out.push("provider calls after running the referenceSearch.trigger action: " + calls);
// The context menu: contextmenu event on the text, then read the menu labels.
const target = document.querySelector(".monaco-editor .view-lines") as HTMLElement;
const rect = target.getBoundingClientRect();
void rect; await editor.getAction("editor.action.showContextMenu")?.run();
await new Promise((r) => setTimeout(r, 600));
const roots: (Document | ShadowRoot)[] = [document];
document.querySelectorAll("*").forEach((el) => { if ((el as HTMLElement).shadowRoot) roots.push((el as HTMLElement).shadowRoot!); });
const labels = roots.flatMap((root) => [...root.querySelectorAll(".action-label")]).map((e) => e.textContent?.trim()).filter(Boolean);
out.push("context menu labels: " + JSON.stringify(labels));
const before = calls;
const item = roots.flatMap((root) => [...root.querySelectorAll(".action-label")]).find((e) => e.textContent?.trim() === "Go to References") as HTMLElement | undefined;
(item?.closest(".action-item") as HTMLElement | null ?? item)?.dispatchEvent(new MouseEvent("mouseup", { bubbles: true, button: 0 }));
item?.click();
await new Promise((r) => setTimeout(r, 800));
out.push(`clicking "Go to References" in the context menu: provider calls ${before} -> ${calls}`);
document.getElementById("result")!.textContent = out.join("\n");
