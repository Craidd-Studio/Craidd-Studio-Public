// Real Tauri shell and native collector; only disposable source/target processes.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn, execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { launch, openSolution, ROOT, processIdentity } from './lib/harness.mjs';
import { showProfiler } from './lib/profiler.mjs';
import { WebDriver } from './lib/webdriver.mjs';

test('Profiling workspace preserves real capture and inspection beside editable source', { timeout: 180000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), 'craidd-profiler-workspace-'));
  await writeFile(join(root, 'Analysis.cln'), '[solution]\nname="Profiler workspace lab"\nversion="1.0"\nprojects=["Analysis.craidd"]\n');
  await writeFile(join(root, 'Analysis.craidd'), '[project]\nname="Analysis"\nlanguage="cpp"\nroot="."\n');
  const file = join(root, 'sample.cpp');
  await writeFile(file, 'int main() { return 42; }\n');
  const markdownFile = join(root, 'Guide.md');
  await writeFile(markdownFile, '# Merged guide\n\nMarkdown and profiling share the editor workspace.\n');
  const executable = join(root, 'collector');
  await promisify(execFile)('g++', ['-std=c++17','-pthread','-I'+join(ROOT,'support/profiling'),join(ROOT,'tests/fixtures/attach-profiling/late_profile_target.cpp'),'-o',executable]);
  const app = await launch('profiler-workspace'); t.after(() => app.close());
  await openSolution(app, join(root,'Analysis.cln'));
  await app.wd.command('POST','/window/rect',{width:1440,height:1050});
  const bridge = await app.invoke('profiling_bridge');
  const child = spawn(executable, [], { env: {...process.env, CRAIDD_PROFILE_SOCKET:bridge}, stdio:['pipe','pipe','pipe'] });
  const exited = new Promise(resolve => child.once('exit', resolve));
  t.after(async () => { child.stdin.end('\n'); await exited; });
  await new Promise((resolve,reject) => { child.stdout.once('data', resolve); child.once('error',reject); });
  const identity = await processIdentity(child.pid);
  await app.invoke('start_profiling', {target:{pid:identity.pid,birth:identity.birth}});
  await showProfiler(app);
  await app.waitFor('real native captures', async () => { const p=await app.invoke('get_profile');return {done:p?.provider&&p.samples.length>=2&&p.captures.length>2,value:p}; });
  const profileId = (await app.invoke('get_profile')).id;
  await app.wd.click(await app.wd.find("//*[@title='"+file+"']"));
  await app.waitFor('source tab',async()=>({done:await app.wd.execute('return !!document.querySelector(".monaco-editor textarea")')}));
  await app.wd.execute('document.querySelector(".monaco-editor textarea").focus()');
  await app.wd.keys(...'// retained edit\n');
  await app.waitFor('dirty source',async()=>({done:await app.wd.execute('return !!document.querySelector("[title=\\"Unsaved changes\\"]")')}));
  await app.wd.click(await app.wd.find("//button[normalize-space()='Open in Editor Panel']"));
  const expanded = () => app.wd.execute('return !!document.querySelector("[aria-label=\\"Expanded Profiler\\"]")');
  await app.waitFor('expanded workspace',async()=>({done:await expanded()}));
  assert.equal(await app.wd.execute('return !!document.querySelector("[aria-label=\\"Right panel\\"]")'),false);
  assert.equal(await app.wd.execute('return document.querySelectorAll("[aria-label=\\"Editor tabs\\"] [role=tab]").length'),2);
  assert.equal(await app.wd.execute('return document.body.innerText.includes("Open in Linked Window")'),false);
  assert.ok(await app.wd.execute('return document.body.textContent.includes("File Discovery") && !!document.querySelector(".profiler-summary-row")'));
  await app.wd.click(await app.wd.find("//button[@aria-label='Take memory snapshot']"));
  await app.wd.execute('const s=document.querySelector("select[aria-label=\\"Profiler view\\"]");s.value=s.options[1].value;s.dispatchEvent(new Event("change",{bubbles:true}));');
  const snapshotId = await app.wd.execute('return document.querySelector("select[aria-label=\\"Profiler view\\"]").value');
  await app.wd.click(await app.wd.find("//button[@role='tab' and normalize-space()='Gold']"));
  await app.wd.execute(`document.querySelector('table[aria-label="Gold hits"] tbody button').scrollIntoView({block:'center'});`);
  await app.wd.click(await app.wd.find("//table[@aria-label='Gold hits']//tbody/tr[1]/td[1]/button"));
  assert.ok(await app.wd.execute('return !!document.querySelector(".profiler-hit-inspector button")'));
  const scopeBefore = await app.wd.execute('return document.querySelector("#profiler-scope").value');
  assert.equal(scopeBefore,'session','row inspection does not change scope');
  await app.wd.click(await app.wd.find("//aside[@aria-label='Selected Gold hit details']//button[normalize-space()='Focus recording']"));
  const recordingId = await app.wd.execute('return document.querySelector("[data-recording-id]").getAttribute("data-recording-id")');
  await app.screenshot('01-expanded-gold');
  // Opening and focusing a split source must never reintroduce the right host.
  await app.wd.execute(`window.__sidebarFlickered=false;window.__workspaceObserver=new MutationObserver(()=>{if(document.querySelector('[aria-label="Right panel"]'))window.__sidebarFlickered=true});window.__workspaceObserver.observe(document.body,{childList:true,subtree:true});
    const row=[...document.querySelectorAll('[title]')].find(el=>el.title===arguments[0]&&el.getAttribute('role')!=='tab');row.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:100,clientY:200}));`,[file]);
  await app.wd.click(await app.wd.find("//button[normalize-space()='Open in Side Window']"));
  await app.waitFor('side code beside Profiling',async()=>({done:await app.wd.execute('return !!document.querySelector(".monaco-editor textarea")')}));
  await app.wd.execute('document.querySelector(".monaco-editor textarea").focus()');
  assert.equal(await expanded(),true);
  app.record('split-focus',await app.wd.execute(`return {sideFocused:!!document.activeElement.closest('[aria-label="Side editor group"]'),flickered:window.__sidebarFlickered}`));
  assert.equal(await app.wd.execute('return window.__sidebarFlickered'),false);
  await app.wd.keys([WebDriver.KEYS.CONTROL,'w']);
  await app.waitFor('side group closed',async()=>({done:await app.wd.execute('return !document.querySelector(".monaco-editor")')}));
  await app.wd.execute('window.__workspaceObserver.disconnect()');
  assert.equal(await expanded(),true);

  await app.wd.click(await app.wd.find("//*[@role='tab' and @title='"+file+"']"));
  await app.waitFor('source and restored sidebar',async()=>({done:await app.wd.execute('return !!document.querySelector(".monaco-editor") && !!document.querySelector("[aria-label=\\"Right panel\\"]")')}));
  assert.equal(await app.wd.execute('return document.querySelector("select[aria-label=\\"Profiler view\\"]").value'),snapshotId);
  assert.equal(await app.wd.execute('return document.querySelector("[data-recording-id]").getAttribute("data-recording-id")'),recordingId);
  assert.ok(await app.wd.execute('return !!document.querySelector("[title=\\"Unsaved changes\\"]")'));
  await app.wd.execute('document.querySelector(".monaco-editor textarea").focus()');
  await app.wd.keys([WebDriver.KEYS.CONTROL,'s']);
  await app.waitFor('saved source',async()=>({done:(await readFile(file,'utf8')).includes('retained edit')}));
  assert.equal((await app.invoke('get_profile')).id,profileId);
  assert.equal((await app.invoke('get_profile')).active,true);
  // Explicit collapsed preference survives workspace activation and close.
  await app.wd.execute('const b=[...document.querySelectorAll("button")].find(b=>b.textContent.trim()==="View");b.click();');
  await app.wd.click(await app.wd.find("//button[normalize-space()='Toggle Debugger & Profiler Panel']"));
  await app.wd.click(await app.wd.find("//*[@role='tab' and @title='Profiling']"));
  await app.waitFor('expanded restored inspection',async()=>({done:await expanded()}));
  assert.equal(await app.wd.execute('return document.querySelector("select[aria-label=\\"Profiler view\\"]").value'),snapshotId);
  assert.ok(await app.wd.execute('return document.querySelector(".profiler-hit-inspector button")!==null'));
  await app.wd.command('POST','/window/rect',{width:900,height:900});
  const narrow = await app.wd.execute(`const p=document.querySelector('.profiler-panel'),g=document.querySelector('.profiler-gold-workspace');return {width:p.clientWidth,scrollWidth:p.scrollWidth,columns:getComputedStyle(g).gridTemplateColumns};`);
  assert.ok(narrow.scrollWidth<=narrow.width+1,'expanded controls do not overflow horizontally');
  assert.equal(narrow.columns.trim().split(/\s+/).length,1,'narrow Gold table/details stack');
  app.record('narrow-expanded',narrow);await app.screenshot('02-narrow-expanded');
  await app.wd.command('POST','/window/rect',{width:1440,height:1050});

  await app.wd.execute('const b=[...document.querySelectorAll("button")].find(b=>b.textContent.trim()==="View");b.click();');
  assert.equal(await app.wd.execute('return [...document.querySelectorAll("button")].find(b=>b.textContent.includes("select another primary tab to show")).disabled'),true);
  await app.wd.keys(WebDriver.KEYS.ESCAPE);
  await app.wd.click(await app.wd.find("//button[@aria-label='Close Profiling']"));
  assert.equal(await app.wd.execute('return !!document.querySelector("[aria-label=\\"Right panel\\"]")'),false);
  assert.equal((await app.invoke('get_profile')).active,true);
  // The shell listener is available while the right host is unmounted.
  await app.wd.execute('window.dispatchEvent(new Event("craidd:show-profiler"))');
  await app.waitFor('shell reveal',async()=>({done:await app.wd.execute('return !!document.querySelector(".profiler-panel")')}));
  assert.equal(await app.wd.execute('return document.querySelector("select[aria-label=\\"Profiler view\\"]").value'),snapshotId);
  await app.screenshot('02-source-and-compact');
  app.record('workspace-verified',{profileId,snapshotId,recordingId,target:identity});
  await app.invoke('stop_profiling');

  // Merge regression: a Markdown file must retain the Docs surface and its
  // source model when the typed Profiling tab takes over the primary host.
  await app.wd.click(await app.wd.find("//*[@title='"+markdownFile+"']"));
  await app.waitFor('Markdown preview',async()=>({done:await app.wd.execute('return !!document.querySelector("[aria-label=\\"Markdown preview\\"]")')}));
  await app.wd.click(await app.wd.find("//button[@aria-label='View Source']"));
  await app.waitFor('Markdown source visible',async()=>({done:await app.wd.execute('const e=document.querySelector("[data-markdown-document] .monaco-editor textarea");return !!e&&e.getBoundingClientRect().width>0')}));
  await app.wd.execute('document.querySelector("[data-markdown-document] .monaco-editor textarea").focus()');
  await app.wd.keys([WebDriver.KEYS.CONTROL,'\uE010'],WebDriver.KEYS.ENTER,...'Merge edit.');
  await app.waitFor('dirty Markdown source',async()=>({done:await app.wd.execute('return !!document.querySelector("[title=\\"Unsaved changes\\"]")')}));
  await app.wd.click(await app.wd.find("//button[normalize-space()='Open in Editor Panel']"));
  await app.waitFor('Profiler beside Markdown tab',async()=>({done:await expanded()}));
  await app.wd.click(await app.wd.find("//*[@role='tab' and @title='"+markdownFile+"']"));
  await app.wd.click(await app.wd.find("//button[@aria-label='View Preview']"));
  await app.waitFor('restored Markdown preview',async()=>({done:await app.wd.execute('return document.querySelector("[aria-label=\\"Markdown preview\\"]")?.innerText.includes("Merged guide")')}));
  await app.wd.keys([WebDriver.KEYS.CONTROL,'s']);
  await app.waitFor('Markdown model survived and saved',async()=>{const saved=await readFile(markdownFile,'utf8');return {done:saved.includes('# Merged guide')&&saved.includes('Merge edit.')};});
  assert.equal((await app.invoke('get_profile')).id,profileId);
  assert.equal((await app.invoke('get_profile')).active,false,'view switching does not restart collection');
  app.record('markdown-profiler-roundtrip',{markdownFile,profileId});
  await app.screenshot('03-markdown-profiler-roundtrip');
});
