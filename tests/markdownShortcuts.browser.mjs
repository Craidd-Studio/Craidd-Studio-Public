  assert.match(await touchPage.evaluate(() => window.docsTest.solution.getState().tabs[0].content), /Touch changed paragraph/);
  console.log("PASS: touch double-tap opens the block; a single tap leaves Preview unchanged; double-tapping another block retains prior edits.");
