  assert.equal(await page.evaluate(() => window.docsTest.solution.getState().tabs.length), 1);
  assert.equal(await page.getByRole("toolbar", { name: "Markdown view" }).count(), 0);
  await page.getByRole("button", { name: "View Source", exact: true }).click();
