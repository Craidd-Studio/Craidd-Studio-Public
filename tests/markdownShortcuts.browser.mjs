  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(String(error)));
  await page.goto(`${process.env.CRAIDD_DOCS_URL || "http://127.0.0.1:1420"}/tests/fixtures/markdown-docs/index.html`);
  const preview = page.getByLabel("Markdown preview", { exact: true });
  await preview.getByRole("heading", { name: "Markdown Docs", exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector('button[aria-label="Edit block at line 3"]').disabled);
  const select = async (word) => preview.evaluate((element, word) => {
    element.focus();
    const walker = document.createTreeWalker(element.querySelector("article"), NodeFilter.SHOW_TEXT);
    let text;
    while (text = walker.nextNode()) {
      const start = text.textContent.indexOf(word);
      if (start < 0) continue;
      const range = document.createRange(); range.setStart(text, start); range.setEnd(text, start + word.length);
      const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range); return;
    }
    throw new Error(`Missing rendered text: ${word}`);
  }, word);
  const original = await page.evaluate(() => window.docsTest.original);
  await preview.getByRole("link", { name: "guide", exact: true }).dispatchEvent("dblclick", { button: 0 });
  assert.equal(await page.getByRole("textbox", { name: "Edit Markdown block", exact: true }).count(), 0);
  await preview.locator("p").filter({ hasText: "A bold paragraph" }).dblclick();
  const blockField = page.getByRole("textbox", { name: "Edit Markdown block", exact: true });
  await blockField.waitFor();
  assert.equal(await blockField.inputValue(), "A **bold** paragraph with [guide](docs/deep/Guide.MARKDOWN#details).");
  assert.equal(await blockField.evaluate((element) => element === document.activeElement), true);
  assert.equal(await page.evaluate(() => window.docsTest.solution.getState().tabs[0].content), original);
  assert.equal(await page.evaluate(() => window.docsTest.solution.getState().tabs[0].dirty), false);
  // A second click inside the editing field keeps normal text selection.
  await blockField.dblclick();
  assert.equal(await blockField.count(), 1);
  await blockField.press("Escape");
  // Switching must translate ranges after a preceding block grows or shrinks.
  await preview.locator("p").filter({ hasText: "A bold paragraph" }).dblclick();
  await blockField.fill("A changed paragraph that is substantially longer than the original paragraph and has additional words.");
  const firstEdit = await page.evaluate(() => window.docsTest.solution.getState().tabs[0].content);
  await preview.getByRole("cell", { name: "One", exact: true }).dblclick();
  assert.equal(await blockField.inputValue(), "| A | B |\n|---|---|\n| One | Two |");
  assert.equal(await blockField.evaluate((element) => element === document.activeElement), true);
  await blockField.fill("| A | B |\n|---|---|\n| Changed | Two |");
  assert.equal(await page.evaluate(() => window.docsTest.solution.getState().tabs[0].content), firstEdit.replace("| One | Two |", "| Changed | Two |"));
  await preview.getByRole("heading", { name: "Markdown Docs", exact: true }).dblclick();
  assert.equal(await blockField.inputValue(), "# Markdown Docs");
  await blockField.fill("# Short");
  await preview.getByRole("cell", { name: "Changed", exact: true }).dblclick();
  assert.match(await blockField.inputValue(), /Changed/);
  await blockField.press("Escape");
  // Each block keeps a separate undo boundary, including a visit with no edit.
  for (let attempt = 0; attempt < 3; attempt++) await page.getByRole("button", { name: "Menu Undo", exact: true }).click();
  await page.waitForFunction((expected) => window.docsTest.solution.getState().tabs[0].content === expected, original);
