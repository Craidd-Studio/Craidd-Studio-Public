  await page.waitForFunction(() => window.docsTest.solution.getState().tabs[0].content.includes("***paragraph***"));
  await page.waitForFunction(() => window.getSelection()?.toString() === "paragraph");
  await page.keyboard.press("Control+i");
  await page.waitForFunction(() => window.docsTest.solution.getState().tabs[0].content.includes("**paragraph**"));
  await page.waitForFunction(() => window.getSelection()?.toString() === "paragraph");
